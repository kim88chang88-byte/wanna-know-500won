/** 풀이에 더해 줄 재료. 없으면 기본 재료(일간·오행)만으로 풀이해요. */
export interface ExtraFacts {
  /** 오늘 날짜(한국 기준). 있으면 오늘의 일진과 내 사주의 관계를 계산해 넣어요. */
  today?: CivilDate;
  /** 신강/신약·용신·대운 등 (ssaju 계산 결과 요약) */
  core?: CoreFacts | null;
}

export function buildUserMessage(chart: SajuChart, topic: ReadingTopic, gender: Gender, concern?: Concern | null, extra: ExtraFacts = {}): string {
  const facts = analyzeChart(chart);
  const payload = {
    오늘뽑은캡슐: TOPIC_LABEL[topic],
    성별: gender === "female" ? "여성" : "남성",
    일간: `${facts.dayMaster.hanja}(${facts.dayMaster.hangul}) · ${facts.dayMaster.elementKo} · ${facts.dayMaster.yinYang === "yang" ? "양" : "음"}`,
    네기둥: facts.pillars.map((p) => `${p.label} ${p.text}`),
    오행분포: {
      목: facts.elementCounts.wood,
      화: facts.elementCounts.fire,
      토: facts.elementCounts.earth,
      금: facts.elementCounts.metal,
      수: facts.elementCounts.water,
    },
    ...(extra.core ? { 사주핵심: extra.core } : {}),
    ...(extra.today ? { 오늘의일진: buildDailyFacts(chart, extra.today) } : {}),
    태어난시간: facts.hourKnown ? "알고 있음" : "모름 (시주 없이 6글자로 본 결과)",
    ...(hasConcern(concern)
      ? { 요즘고민: { 고른항목: concern.tags.map(concernLabel), 직접쓴말: concern.text || "없음" } }
      : {}),
    절기경계: chart.uncertainPillars.length > 0 ? "태어난 날 절기가 바뀌어 연·월 기둥이 확정되지 않았을 수 있음" : "해당 없음",
  };
  const focus =
    topic === "general"
      ? "특별히 고른 주제는 없으니 총운 중심으로 균형 있게 써줘."
      : `이번에는 "${TOPIC_LABEL[topic]}" 캡슐을 뽑았으니, 도리 한마디와 총운 요약에서 이 주제를 조금 더 살려줘.`;

  const focusConcern = hasConcern(concern) ? "\n사용자가 적은 '요즘 고민'에 공감하며 도리 한마디가 그 고민에 닿게 해줘." : "";
  return `계산된 사주 정보:\n${JSON.stringify(payload, null, 2)}\n\n${focus}${focusConcern}\n총운, 연애운, 금전운, 마음운, 오늘의 키워드, 도리 한마디, 도리가 본 이유, 요약하자면 문단을 써줘.`;
}
