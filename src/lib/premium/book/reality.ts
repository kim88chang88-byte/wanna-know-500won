import type { RealityCheck } from "../types";

/*
 * '사주 vs 지금 내 현실' 3갈래. 사주가 보여 준 흐름은 그대로 두고, 읽는 사람이 현재 모습과 견줘 보게 해요.
 *  - 아직 못 미쳐요  → 더 커질 여지가 있다는 응원 + 이 흐름을 잡을 작은 행동
 *  - 딱 맞아요      → "거봐요, 맞죠?" + 지키면서 다음 걸음 준비
 *  - 이미 넘어섰어요 → 타고난 흐름보다 잘 살아온 걸 칭찬 + 유지·발전
 * 금액이나 나이처럼 사주로 계산할 수 없는 숫자는 쓰지 않고, 겁주지 않아요.
 */

