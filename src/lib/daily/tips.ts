export const TIPS_PER_GOD = 12;

/** 오늘 일진 천간의 오행으로 정하는 오늘의 색 */
const STEM_COLOR: Record<string, string> = { 甲: "초록", 乙: "초록", 丙: "코랄", 丁: "코랄", 戊: "노랑", 己: "노랑", 庚: "은빛", 辛: "은빛", 壬: "파랑", 癸: "파랑" };

/** "丙午(병오)" 같은 일진에서 오늘의 색을 구해요. 알 수 없으면 "하늘색". */
export function colorOfGanzhi(ganzhi: string): string {
  return STEM_COLOR[ganzhi.trim().charAt(0)] ?? "하늘색";
}

/** 문장 속 빈칸을 오늘 값으로 채워요. */
export function fillTip(text: string, luck: number, color: string): string {
  return text.replace(/\{색\}/g, color).replace(/\{숫자\}/g, String(luck)).replace(/\{끝자리\}/g, String(luck % 10 || 5));
}
